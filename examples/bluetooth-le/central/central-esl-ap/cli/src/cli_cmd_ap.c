            ocap_cmd.param.write.mode = 1;
            ocap_cmd.param.write.rfu = 0;
            ocap_cmd.param.write.rfu_1 = 0;
            ocap_cmd.opcode = OACP_OPCODE_WRITE;
            while (object_action_control_point_cmd_send((uint8_t*)&ocap_cmd, sizeof(ots_oacp_calculate_write_t) + sizeof(uint8_t)) != BLE_ERR_OK);
