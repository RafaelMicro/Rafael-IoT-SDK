static int _cli_cmd_scan_all_device(int argc, char **argv, cb_shell_out_t log_out, void *pExtra)
{
    uint8_t enable;

    do
    {
        if (argc < 2)
        {
            printf("Invalid parameter\n");
            break;
        }

        enable = (*(argv[1] + 1) == 'x')
                 ? utility_strtox(argv[1] + 2, 0, 2)
                 : utility_strtol(argv[1], 0);

        if (enable == 1)
        {
            ble_scan_param_t scan_param;
            ble_gap_addr_t addr_param;

            ble_cmd_device_addr_get(&addr_param);
            scan_param.scan_type = SCAN_TYPE_ACTIVE;
            scan_param.own_addr_type = addr_param.addr_type;
            scan_param.scan_filter_policy = SCAN_FILTER_POLICY_BASIC_UNFILTERED;
            scan_param.scan_interval = 100U;       // 100*0.625ms=62.5ms;
            scan_param.scan_window = 100U;       // 100*0.625ms=62.5ms;
            ble_cmd_scan_param_set(&scan_param);
            ble_cmd_scan_enable();
        }
        else
        {
            ble_cmd_scan_disable();
        }
    
    } while (0);

    return 0;
}

