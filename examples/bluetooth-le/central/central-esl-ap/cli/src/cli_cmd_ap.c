static int _cli_cmd_sync_start(int argc, char **argv, cb_shell_out_t log_out, void *pExtra)
{
    ble_err_t status;
    uint8_t enable;
    ap_sync_start_t *p_sync_start;
    do
    {
        enable = (*(argv[1] + 1) == 'x')
                 ? utility_strtox(argv[1] + 2, 0, 2)
                 : utility_strtol(argv[1], 0);

        if (enable == 0)
        {
            status = ap_sync_stop();
            printf("ap sync stop result: %d\n", status);
        }
        else
        {
            p_sync_start = pvPortMalloc(sizeof(ap_sync_start_t));
            if (p_sync_start == NULL)
            {
                printf("p_sync_start malloc fail\n");
                break;
            }

            p_sync_start->padv_interval = 3200; // 3200*1.25ms = 4s
            p_sync_start->num_subevents = 15;
            p_sync_start->subevent_interval = 184; //184*1.25ms = 230ms 
            p_sync_start->rsp_slot_delay = 14; //14*1.25=17.5ms 
            p_sync_start->rsp_slot_spacing = 24; //24 * 0.125ms = 3ms
            p_sync_start->num_rsp_slot = MAX_RSP_SLOT;      
            status = ap_sync_start(p_sync_start);
            printf("ap sync start result: %d\n", status);
            vPortFree(p_sync_start);

        }
    } while (0);

    return 0;
}

